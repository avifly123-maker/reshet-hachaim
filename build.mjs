// Usage:
//   node build.mjs [entry.js] [out.html] [--dev] [--artifact]
//       ONE self-contained offline HTML file (everything inlined, including three.js, the packs and every picture).
//       --artifact also writes <out>.artifact.html (no document skeleton – the artifact host adds its own).
//   node build.mjs --desktop [outdir] [--dev]
//       The desktop app folder (default desktop/app/), served by desktop/main.js over app://game/:
//         index.html            page + styles (fonts as files)
//         core.js + chunks/     engine, UI, start screen, players, audio (chunks/ = code shared by core and packs)
//         packs/<name>.js       one ES module per pack (src/packs/*.js): each zone, and the learning hub
//         assets/…              every embedded picture / font as a real file (webp/png/woff2)
//         migrate.html          empty page main.js uses to carry saves over from the old file:// storage
//       icon.png (and anything else not generated here) is left alone.
// Both builds run the same code: core/packs.js import()s the packs; esbuild inlines those imports in the single file.
import * as esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';

const flags = process.argv.slice(2).filter(a => a.startsWith('--'));
const args = process.argv.slice(2).filter(a => !a.startsWith('--'));
const dev = flags.includes('--dev');
// --edition=torah: מהדורה תורנית (content from the sources, src/data/torah.js; src/core/edition.js)
const EDITION = (flags.find(f => f.startsWith('--edition=')) || '--edition=general').split('=')[1];
if (!['general', 'torah'].includes(EDITION)) throw new Error('unknown edition ' + EDITION);
const DEFINE = { __EDITION__: JSON.stringify(EDITION) };
// the general edition carries none of the torah edition's pictures
const editionPlugin = { name: 'edition-assets', setup(b) {
  if (EDITION !== 'torah') b.onLoad({ filter: /[\\/]src[\\/]data[\\/]source-art\.js$/ }, () => ({ contents: 'export const SOURCE_ART = {};', loader: 'js' }));
} };
const title = EDITION === 'torah' ? 'רשת החיים – מהדורה תורנית' : 'רשת החיים';
const BASE_CSS = 'html,body{margin:0;height:100%;overflow:hidden;background:#0d1a14;}canvas#game{display:block;position:fixed;inset:0;width:100%;height:100%;touch-action:none}';
const readCss = (fontsCss) => {
  let css = '';
  // embedded fonts (base64 woff2, generated by src/ui/fonts-build.mjs) go first, then the UI styles
  if (fs.existsSync('src/ui/fonts.css')) css += fontsCss ? fontsCss(fs.readFileSync('src/ui/fonts.css', 'utf8')) : fs.readFileSync('src/ui/fonts.css', 'utf8');
  if (fs.existsSync('src/ui/style.css')) css += fs.readFileSync('src/ui/style.css', 'utf8');
  if (fs.existsSync('src/research/research.css')) css += fs.readFileSync('src/research/research.css', 'utf8');   // חוקרי היער
  if (fs.existsSync('src/lab/lab.css')) css += fs.readFileSync('src/lab/lab.css', 'utf8');   // מעבדת רובו־דע
  return css;
};
const MB = (n) => (n / 1024 / 1024).toFixed(2) + ' MB';
const KB = (n) => (n / 1024).toFixed(0) + ' KB';

if (flags.includes('--desktop')) await buildDesktop(args[0] || 'desktop/app');
else await buildSingle(args[0] || 'src/main.js', args[1] || (EDITION === 'torah' ? 'dist/index-torah.html' : 'dist/index.html'));

// ───────────────────────────────────────────────────────────── single self-contained HTML file
async function buildSingle(entry, out) {
  const r = await esbuild.build({
    entryPoints: [entry], bundle: true, write: false, format: 'iife',
    minify: !dev, target: 'es2019', legalComments: 'none', charset: 'utf8',
    logLevel: 'warning', plugins: [editionPlugin], define: DEFINE,
  });
  const js = r.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const css = readCss();
  const html = `<!doctype html>
<html lang="he" dir="rtl"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<title>${title}</title>
<style>${BASE_CSS}${css}</style>
</head><body><canvas id="game"></canvas><div id="ui"></div>
<script>${js}</script></body></html>`;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  if (flags.includes('--artifact')) {
    // artifact host adds its own document skeleton: emit only title, styles and content
    const art = `<title>${title}</title>
<style>:root{color-scheme:dark}${BASE_CSS}${css}</style>
<canvas id="game"></canvas><div id="ui" dir="rtl" lang="he"></div>
<script>${js}</script>`;
    fs.writeFileSync(out.replace(/\.html$/, '.artifact.html'), art);
  }
  console.log(`built ${out} (${MB(html.length)})`);
}

// ───────────────────────────────────────────────────────────── desktop: core + packs + asset files
async function buildDesktop(outdir) {
  // generated paths only – icon.png and anything else in the folder stays
  for (const p of ['index.html', 'core.js', 'migrate.html', 'packs', 'chunks', 'assets', 'build-info.json']) fs.rmSync(path.join(outdir, p), { recursive: true, force: true });
  fs.mkdirSync(outdir, { recursive: true });
  const assets = new Map();   // published path → bytes
  const ext = { 'image/webp': 'webp', 'image/png': 'png', 'image/jpeg': 'jpg', 'image/svg+xml': 'svg', 'font/woff2': 'woff2' };
  const toFile = (dataUri, rel) => {
    const m = /^data:([^;,]+);base64,(.*)$/s.exec(dataUri);
    if (!m || !ext[m[1]]) return dataUri;
    const p = `assets/${rel}.${ext[m[1]]}`;
    assets.set(p, Buffer.from(m[2], 'base64'));
    return p;   // relative to index.html (app://game/)
  };
  // The generated picture tables (src/data/*.js written by tools/build-*.py) hold base64 data URIs; in the desktop build
  // each module is replaced by the same table with file paths, so a picture costs nothing until something shows it.
  const ASSET_MODULES = /[\\/]src[\\/]data[\\/](panorama|ground-textures|card-art|thumbs|island-art|tree-shadow|logo|pack-art|source-art|lab-art|reef-backdrop)\.js$/;
  const assetPlugin = {
    name: 'asset-files',
    setup(b) {
      b.onLoad({ filter: ASSET_MODULES }, async (a) => {
        const name = path.basename(a.path, '.js');
        // the tables are plain literals (no imports): evaluated as a data: module, so Node needs no package type
        const mod = await import('data:text/javascript;base64,' + fs.readFileSync(a.path).toString('base64'));
        const walk = (v, keys) => {
          if (typeof v === 'string') return v.startsWith('data:') ? toFile(v, [name, ...keys].join('/')) : v;
          if (Array.isArray(v)) return v.map((x, i) => walk(x, [...keys, String(i)]));
          if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x, [...keys, k])]));
          return v;
        };
        const exp = Object.entries(mod).map(([k, v]) => `export const ${k} = ${JSON.stringify(walk(v, Object.keys(mod).length > 1 ? [k] : []))};`);
        return { contents: `// ${name}: generated by build.mjs --desktop (pictures as files under assets/${name}/)\n${exp.join('\n')}\n`, loader: 'js' };
      });
    },
  };
  const packs = fs.readdirSync('src/packs').filter(f => f.endsWith('.js')).map(f => f.replace(/\.js$/, ''));
  const entryPoints = { core: 'src/main.js', ...Object.fromEntries(packs.map(p => [`packs/${p}`, `src/packs/${p}.js`])) };
  const r = await esbuild.build({
    entryPoints, bundle: true, splitting: true, format: 'esm', outdir, write: true, metafile: true,
    chunkNames: 'chunks/[name]-[hash]', minify: !dev, target: 'chrome120', legalComments: 'none', charset: 'utf8',
    logLevel: 'warning', plugins: [editionPlugin, assetPlugin], define: DEFINE,
  });
  // fonts: files + <link rel=preload> so the start screen never shows a fallback font
  const fonts = [];
  let fontN = 0;
  const css = readCss((src) => src.replace(/@font-face\{[^}]*\}/g, (block) => {
    const fam = (/font-family:"?([^";]+)"?/.exec(block) || [, 'font'])[1];
    const w = (/font-weight:(\d+)/.exec(block) || [, '400'])[1];
    return block.replace(/url\((data:font\/woff2;base64,[^)]+)\)/, (all, uri) => { const p = toFile(uri, `fonts/${fam}-${w}-${fontN++}`); fonts.push(p); return `url(${p})`; });
  }));
  for (const [p, buf] of assets) { fs.mkdirSync(path.join(outdir, path.dirname(p)), { recursive: true }); fs.writeFileSync(path.join(outdir, p), buf); }
  const html = `<!doctype html>
<html lang="he" dir="rtl"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<title>${title}</title>
${fonts.map(f => `<link rel="preload" href="${f}" as="font" type="font/woff2" crossorigin>`).join('\n')}
<style>${BASE_CSS}${css}</style>
<script type="module" src="core.js"></script>
</head><body><canvas id="game"></canvas><div id="ui"></div></body></html>`;
  fs.writeFileSync(path.join(outdir, 'index.html'), html);
  fs.writeFileSync(path.join(outdir, 'migrate.html'), '<!doctype html><meta charset="utf-8"><title>migrate</title>\n');

  // size report: core = core.js + the chunks it imports statically; a pack = its file + the chunks only it adds
  const outs = r.metafile.outputs;
  const rel = (p) => path.relative(outdir, p).split(path.sep).join('/');
  const closure = (file, seen = new Set()) => { if (seen.has(file)) return seen; seen.add(file); for (const i of outs[file].imports) if (i.kind === 'import-statement') closure(i.path, seen); return seen; };
  const size = (set) => [...set].reduce((n, f) => n + outs[f].bytes, 0);
  const coreFile = Object.keys(outs).find(f => rel(f) === 'core.js');
  const core = closure(coreFile);
  const info = { core: { files: [...core].map(rel), bytes: size(core) }, packs: {}, html: html.length, assets: {} };
  for (const p of packs) {
    const f = Object.keys(outs).find(o => rel(o) === `packs/${p}.js`);
    const own = [...closure(f)].filter(x => !core.has(x));
    info.packs[p] = { files: own.map(rel), bytes: own.reduce((n, x) => n + outs[x].bytes, 0) };
  }
  for (const [p, buf] of assets) { const g = path.posix.dirname(p); info.assets[g] = (info.assets[g] || 0) + buf.length; }
  // nothing big may stay inlined in the code
  for (const f of Object.keys(outs)) {
    if (!f.endsWith('.js')) continue;
    const big = (fs.readFileSync(f, 'utf8').match(/data:[a-z]+\/[a-z0-9.+-]+;base64,[A-Za-z0-9+/=]{20000,}/g) || []).length;
    if (big) console.warn(`warning: ${rel(f)} still holds ${big} large inlined data URI(s)`);
  }
  fs.writeFileSync(path.join(outdir, 'build-info.json'), JSON.stringify(info, null, 1));
  const assetBytes = [...assets.values()].reduce((n, b) => n + b.length, 0);
  console.log(`built ${outdir}/ (desktop)\n  index.html ${KB(html.length)}\n  core       ${KB(info.core.bytes)}  (${info.core.files.join(', ')})`);
  for (const [p, v] of Object.entries(info.packs)) console.log(`  pack ${p.padEnd(7)}${KB(v.bytes)}  (${v.files.join(', ')})`);
  console.log(`  assets     ${MB(assetBytes)} in ${assets.size} files`);
}
