// 1.4.4 set 9: the rare badges are earned from the badges a child owns (badges-store.js checkRare).
const mem = {};
globalThis.localStorage = { getItem: (k) => (k in mem ? mem[k] : null), setItem: (k, v) => { mem[k] = String(v); }, removeItem: (k) => { delete mem[k]; }, key: (i) => Object.keys(mem)[i], get length() { return Object.keys(mem).length; } };
const fired = [];
globalThis.window = { dispatchEvent: (e) => fired.push(e.detail), localStorage: globalThis.localStorage };
globalThis.CustomEvent = class { constructor(t, o) { this.type = t; this.detail = o && o.detail; } };
const { BADGES, FRAMES } = await import('../../src/data/badges.js');
const { MEDAL_ART } = await import('../../src/data/medal-art.js');
const { FRAME_ART } = await import('../../src/data/frame-art.js');
const S = await import('../../src/core/badges-store.js');
let bad = 0; const ok = (c, m) => { if (!c) { bad++; console.log('FAIL', m); } };
const rare = BADGES.filter((b) => b.group === 'rare');
ok(rare.length === 17, 'seventeen rare badges (1.3.3)');
for (const b of rare) ok(MEDAL_ART[b.rare.metal + '_' + b.rare.emblem], 'medal art ' + b.id);
for (const f of FRAMES) if (f.id !== 'none') ok(FRAME_ART[f.id], 'frame art ' + f.id);
ok(S.checkRare().length === 0, 'nothing for a new player');
const plain = BADGES.filter((b) => b.group !== 'rare' && !b.torah);
const grove = plain.filter((b) => b.group === 'grove');
grove.slice(0, Math.ceil(grove.length / 2)).forEach((b) => S.grant(b.earn));
ok(S.hasBadge('r_h_grove') && !S.hasBadge('r_a_grove'), 'half of the grove');
grove.forEach((b) => S.grant(b.earn));
ok(S.hasBadge('r_a_grove'), 'all of the grove');
ok(fired.includes('r_a_grove'), 'the rare badge is announced');
plain.forEach((b) => S.grant(b.earn));
const miss = rare.filter((b) => !S.hasBadge(b.id)).map((b) => b.id);
ok(!miss.length, 'every rare badge can be earned: ' + miss.join(','));
ok(S.groupCount('rare') === 17 && FRAMES.filter((f) => f.group === 'rare').every(S.frameOpen), 'rare frames open');
console.log(bad ? 'rare badges FAIL ' + bad : 'rare badges ok ' + rare.length);
process.exit(bad ? 1 : 0);
