// Generates src/ui/fonts.css: the game's two typefaces embedded as base64 woff2, so the single HTML file needs no network.
//   Suez One (display: titles, headings, numbers) and Rubik 400/700 (text) – both SIL Open Font License 1.1, from Fontsource.
// Usage (once, when changing fonts):
//   mkdir /tmp/f && cd /tmp/f && npm i @fontsource/suez-one @fontsource/rubik
//   node src/ui/fonts-build.mjs /tmp/f/node_modules
// build.mjs prepends fonts.css to style.css.
import fs from 'fs';
import path from 'path';
const nm = process.argv[2] || 'node_modules';
// Fontsource unicode ranges: Hebrew letters + the basic Latin block (digits and punctuation live there)
const HEB = 'U+0307-0308,U+0590-05FF,U+200C-2010,U+20AA,U+25CC,U+FB1D-FB4F';
const LAT = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const faces = [
  ['wol-display', 'suez-one', 'suez-one', 400],
  ['wol-text', 'rubik', 'rubik', 400],
  ['wol-text', 'rubik', 'rubik', 700],
];
let css = '/* generated by src/ui/fonts-build.mjs – Suez One & Rubik, SIL OFL 1.1 (fontsource.org) */\n';
for (const [fam, pkg, file, w] of faces) {
  for (const [sub, range] of [['hebrew', HEB], ['latin', LAT]]) {
    const p = path.join(nm, '@fontsource', pkg, 'files', `${file}-${sub}-${w}-normal.woff2`);
    const b64 = fs.readFileSync(p).toString('base64');
    css += `@font-face{font-family:"${fam}";font-style:normal;font-weight:${w};font-display:swap;src:url(data:font/woff2;base64,${b64}) format("woff2");unicode-range:${range}}\n`;
  }
}
fs.writeFileSync(new URL('./fonts.css', import.meta.url), css);
console.log('fonts.css', (css.length / 1024).toFixed(1), 'KB');
