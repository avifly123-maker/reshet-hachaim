#!/usr/bin/env python3
"""Packs the background music (art/music/*.ogg, made by tools/music/compose.py) into src/data/music.js.

    python3 tools/build-music.py

src/data/music.js is an asset module (build.mjs ASSET_MODULES): in the one-file build the music rides inside the page
as base64; in the desktop build each piece becomes a file under assets/music/. Nothing is fetched or decoded until a
piece is about to play (src/audio/music.js imports this module lazily).
"""
import base64
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'art', 'music')
OUT = os.path.join(ROOT, 'src', 'data', 'music.js')

table = {}
for name in ('start', 'lab'):
    with open(os.path.join(SRC, name + '.json')) as f:
        info = json.load(f)
    with open(os.path.join(SRC, name + '.ogg'), 'rb') as f:
        b64 = base64.b64encode(f.read()).decode('ascii')
    # the file holds PAD seconds of the loop's end, the loop, then PAD seconds of its start: play loopStart..loopEnd
    table[name] = {'src': 'data:audio/ogg;base64,' + b64, 'loopStart': info['pad'], 'loopEnd': round(info['pad'] + info['loop'], 5)}

with open(OUT, 'w') as f:
    f.write('// GENERATED by tools/build-music.py from art/music/ (tools/music/compose.py) – do not edit.\n')
    f.write('// Background music: the start screen and the lab of רובו־דע. Opus in Ogg; loop between loopStart and loopEnd (seconds).\n')
    f.write('export const MUSIC = ' + json.dumps(table, separators=(',', ':')) + ';\n')
print('wrote', OUT, f'{os.path.getsize(OUT) / 1024:.0f} KB')
