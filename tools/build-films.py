#!/usr/bin/env python3
# The short films of 1.4.4 set 11: art/films/raw/<id>.mp4 (Gemini/Veo, 1280x720, about 8-10 s) → the whole clip at
# 960x540, WebM VP9 without sound (a crossfaded loop ghosted the moving camera; src/ui/loading-film.js dips and restarts) → art/films/<id>.webm → one asset module
# src/data/film-art.js (FILMS: id → data URI; the desktop build turns them into files).
#   python3 tools/build-films.py            all raw films (only those whose webm is missing or older)
#   python3 tools/build-films.py amazon lab  just these
# The raw clips are not committed (art/films/raw is in .gitignore): they stay on Avi's PC in Documents\reshet-hachaim-1.4\art\films.
import base64, os, subprocess, sys
RAW, OUT, MOD = 'art/films/raw', 'art/films', 'src/data/film-art.js'
ids = sys.argv[1:] or sorted(f[:-4] for f in os.listdir(RAW) if f.endswith('.mp4'))
for i in ids:
    src, dst = f'{RAW}/{i}.mp4', f'{OUT}/{i}.webm'
    if not os.path.exists(src): continue
    if not sys.argv[1:] and os.path.exists(dst) and os.path.getmtime(dst) > os.path.getmtime(src): continue
    fl = '[0:v]scale=960:540:flags=lanczos,fps=24,format=yuv420p[v]'
    subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-i', src, '-filter_complex', fl, '-map', '[v]', '-an',
                           '-c:v', 'libvpx-vp9', '-b:v', '0', '-crf', '38', '-row-mt', '1', '-deadline', 'good', '-cpu-used', '2', dst])
    print(i, os.path.getsize(dst) // 1024, 'KB')
films = sorted(f[:-5] for f in os.listdir(OUT) if f.endswith('.webm'))
with open(MOD, 'w') as f:
    f.write('// Generated by tools/build-films.py from art/films/*.webm (1.4.4 set 11). Do not edit by hand.\nexport const FILMS = {\n')
    for i in films:
        f.write(f'  "{i}": "data:video/webm;base64,{base64.b64encode(open(f"{OUT}/{i}.webm", "rb").read()).decode()}",\n')
    f.write('};\n')
print('films:', ', '.join(films), os.path.getsize(MOD) // 1024, 'KB')
