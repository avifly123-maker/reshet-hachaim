#!/usr/bin/env python3
"""Packs ניצוץ's voice into src/data/nitzotz-voice.js.

    python3 tools/build-nitzotz-voice.py <clips.json>

6.11 (Avi: "a ready voice from Gemini Studio, full of feeling and excitement; an adult voice is fine"): the lines of
src/data/guide/workshop.js were spoken in Google AI Studio's speech generator (Gemini TTS, the voice "Mako", a style
prompt of excitement), one clip per line id and one per `<id>.k` (the beginners' vocalised words). The page saved them as
one JSON file { id: "data:audio/wav;base64,..." } (a single download). Here every clip is trimmed of silence at its
ends, levelled to the loudness of רובו־דע's lines and encoded as Opus in Ogg, like src/data/voice.js.
"""
import base64, json, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'data', 'nitzotz-voice.js')
clips = json.load(open(sys.argv[1]))
tmp = tempfile.mkdtemp(prefix='nzv-')
table = {}
for cid, url in sorted(clips.items()):
    raw = base64.b64decode(url.split(',', 1)[1])
    wav = os.path.join(tmp, cid + '.wav'); ogg = os.path.join(tmp, cid + '.ogg')
    open(wav, 'wb').write(raw)
    af = ('silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05,areverse,'
          'silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08,areverse,'
          'loudnorm=I=-18:TP=-2:LRA=11,afade=t=in:d=0.01')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', wav, '-af', af, '-ar', '48000', '-ac', '1', '-c:a', 'libopus', '-b:a', '32k',
                    '-application', 'voip', '-map_metadata', '-1', ogg], check=True)
    table[cid] = {'src': 'data:audio/ogg;base64,' + base64.b64encode(open(ogg, 'rb').read()).decode('ascii')}
with open(OUT, 'w') as f:
    f.write('// GENERATED by tools/build-nitzotz-voice.py – do not edit. ניצוץ\'s voice: Gemini TTS (Google AI Studio, the voice\n')
    f.write('// "Mako" with a style prompt of excitement), one clip per line id of src/data/guide/workshop.js and <id>.k for the\n')
    f.write('// beginners\' words. Opus in Ogg.\n')
    f.write('export const NITZ_VOICE = ' + json.dumps(table, separators=(',', ':')) + ';\n')
print('wrote', OUT, len(table), 'clips', f'{os.path.getsize(OUT) / 1024:.0f} KB')
