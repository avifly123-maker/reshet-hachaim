#!/usr/bin/env python3
# art/robolab/code_hero.png (tools/blender/code_hero.py) → src/data/robolab/code-hero.js (webp, as wk-hero.js)
import base64, io, sys
from PIL import Image
src = sys.argv[1] if len(sys.argv) > 1 else 'art/robolab/code_hero.png'
im = Image.open(src).convert('RGB')
if src != 'art/robolab/code_hero.png': im.save('art/robolab/code_hero.png')
b = io.BytesIO(); im.save(b, 'WEBP', quality=80)
open('src/data/robolab/code-hero.js', 'w').write("// The robot lab's programming lessons picture (tools/blender/code_hero.py, 6.11). Generated by tools/build-code-hero.py; do not edit.\nexport const CODE_HERO = 'data:image/webp;base64," + base64.b64encode(b.getvalue()).decode() + "';\n")
print('code-hero.js', len(b.getvalue()) // 1024, 'KB')
