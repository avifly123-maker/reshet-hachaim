#!/usr/bin/env python3
"""The robot workshop's part icons -> src/data/robolab/wk-icons.js
Input: art/robolab/icons/<partId>.png, rendered on the owner's PC by rl_wk_icon() in tools/blender/robolab_wk.py
(256 px, transparent). Each is trimmed to its picture, centred on a square with a small margin, scaled to 144 px and
stored as webp (with alpha). Output: export const WK_ICONS = { <partId>: 'data:image/webp;base64,...' }
usage: python3 tools/build-wk-icons.py"""
import base64, io, json, pathlib
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'art/robolab/icons'
OUT = ROOT / 'src/data/robolab/wk-icons.js'
PX = 144

def pack(p):
    im = Image.open(p).convert('RGBA')
    bb = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox() or (0, 0, im.width, im.height)
    im = im.crop(bb); side = int(max(im.size) * 1.12)
    sq = Image.new('RGBA', (side, side), (0, 0, 0, 0)); sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    sq = sq.resize((PX, PX), Image.LANCZOS)
    b = io.BytesIO(); sq.save(b, 'WEBP', quality=82, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()

icons = {p.stem: pack(p) for p in sorted(SRC.glob('*.png'))}
OUT.write_text('// generated by tools/build-wk-icons.py from art/robolab/icons (Blender: tools/blender/robolab_wk.py rl_wk_icon)\n'
               '// the robot workshop\'s part icons, one per catalogue part (src/data/robolab/workshop.js)\n'
               'export const WK_ICONS = ' + json.dumps(icons, separators=(',', ':')) + ';\n', encoding='utf-8')
print('workshop icons: %d, %d KB' % (len(icons), OUT.stat().st_size // 1024))
