#!/usr/bin/env python3
"""Pack the Blender ground bakes (art/ground/*_a.png albedo, *_n.png normal) into src/data/ground-textures.js.

Per biome: A = litter (amazon) / grass (grove), B = moss (amazon) / limestone (grove).
avgA/avgB are the mean *linear* colours (the shader divides by them to keep the game's own palette as the mean tone).
"""
import base64, io, json, os
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'ground')
OUT = os.path.join(ROOT, 'src', 'data', 'ground-textures.js')
SIZE = 512
SETS = {
    'amazon': {'a': 'litter', 'b': 'moss', 'tile': [3.2, 2.6], 'nk': 0.85},
    'grove': {'a': 'grass', 'b': 'lime', 'tile': [2.8, 4.2], 'nk': 0.8},
    'reef': {'a': 'reefsand', 'b': 'reefrubble', 'tile': [3.4, 2.6], 'nk': 0.9},
}

def url(im, q):
    b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), len(b.getvalue())

def lin_mean(im):
    a = np.asarray(im, dtype=np.float32) / 255.0
    lin = np.where(a <= 0.04045, a / 12.92, ((a + 0.055) / 1.055) ** 2.4)
    return [round(float(v), 4) for v in lin.reshape(-1, 3).mean(0)]

def normal(path):
    im = Image.open(path).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.6))
    n = np.asarray(im, dtype=np.float32) / 255.0 * 2 - 1
    n[..., 2] = np.maximum(n[..., 2], 0.05)                          # no back-facing normals
    n /= np.linalg.norm(n, axis=2, keepdims=True)
    return Image.fromarray(((n * 0.5 + 0.5) * 255 + 0.5).astype(np.uint8), 'RGB')

out, total = {}, 0
for biome, s in SETS.items():
    e = {'tile': s['tile'], 'nk': s['nk']}
    ok = True
    for slot in ('a', 'b'):
        name = s[slot]
        pa, pn = os.path.join(ART, name + '_a.png'), os.path.join(ART, name + '_n.png')
        if not (os.path.exists(pa) and os.path.exists(pn)): ok = False; break
        alb = Image.open(pa).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS)
        e[slot], n1 = url(alb, 82); e[slot + 'n'], n2 = url(normal(pn), 88)
        e['avg' + slot.upper()] = lin_mean(alb); total += n1 + n2
        print(f'{biome}/{slot} {name}: albedo {n1 // 1024} KB, normal {n2 // 1024} KB')
    if ok: out[biome] = e
with open(OUT, 'w') as f:
    f.write('// Generated by tools/build-ground-textures.py from art/ground/ (Blender bakes). Do not edit by hand.\n')
    f.write('export const GROUND_TEX = ' + json.dumps(out) + ';\n')
print('total images', total // 1024, 'KB; wrote', OUT, os.path.getsize(OUT) // 1024, 'KB')
