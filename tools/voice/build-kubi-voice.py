#!/usr/bin/env python3
"""קוּבִּי's recorded lines -> src/data/kubi-voice.js
Input: a folder of <id>.wav from cb_say.py (Chatterbox on the owner's PC) and the list from kubi-lines.mjs.
Each wav is trimmed of silence, made mono 24 kHz Opus (like רובו־דע's voice) and stored as a data URI.
A line whose audio is far too short for its words (the model sometimes stops early) is reported and left out, so the
game shows the words without a broken sound; record it again and run this once more.
usage: python3 tools/voice/build-kubi-voice.py <wav_dir> <lines.json> [--min-cps 7]"""
import sys, json, base64, subprocess, pathlib, wave, tempfile, os
ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
OUT = ROOT / 'src/data/kubi-voice.js'
ART = ROOT / 'art/voice-kubi'

def dur(p):   # Chatterbox writes 32-bit float wavs, which the wave module cannot read
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(p)], capture_output=True, text=True)
    return float(r.stdout.strip() or 0)

def main():
    wdir = pathlib.Path(sys.argv[1]); lines = json.load(open(sys.argv[2], encoding='utf-8'))
    max_cps = 22.0   # letters (without nikud) per second: more than this means the audio was cut short
    ART.mkdir(parents=True, exist_ok=True)
    out, bad, missing = {}, [], []
    for L in lines:
        i = L['id']
        if i.startswith('test_'): continue
        p = wdir / (i + '.wav')
        if not p.exists(): missing.append(i); continue
        letters = sum(1 for ch in L['text'] if 'א' <= ch <= 'ת')
        d = dur(p)
        if d <= 0.3 or letters / max(d, 0.1) > max_cps: bad.append((i, round(d, 1), letters)); continue
        ogg = ART / (i + '.ogg')
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', str(p), '-af', 'silenceremove=start_periods=1:start_threshold=-45dB:stop_periods=-1:stop_threshold=-45dB:stop_duration=0.4',
                        '-ac', '1', '-ar', '24000', '-c:a', 'libopus', '-b:a', '28k', '-application', 'voip', str(ogg)], check=True)
        out[i] = 'data:audio/ogg;base64,' + base64.b64encode(ogg.read_bytes()).decode()
    js = ('// GENERATED by tools/voice/build-kubi-voice.py from art/voice-kubi/ – the lines of קוּבִּי (Chatterbox Multilingual, MIT;\n'
          '// the voice follows the preview of the owner\'s ElevenLabs voice "Robo-Da"). Opus in Ogg, one entry per line id.\n'
          'export const KUBI_VOICE = ' + json.dumps({k: {'src': v} for k, v in out.items()}, separators=(',', ':')) + ';\n')
    OUT.write_text(js)
    print('kubi voice: %d lines, %d KB; too short: %d %s; missing: %d' % (len(out), len(js) // 1024, len(bad), bad[:12], len(missing)))
    if bad: json.dump([b[0] for b in bad], open(wdir / 'redo.json', 'w'))

if __name__ == '__main__':
    main()
