#!/usr/bin/env python3
"""The reef's surroundings, rendered in Blender (tools/blender/reef_seabed.py) → src/data/reef-backdrop.js
  art/reef/seabed_top.png   the sea floor from straight above, 300 m across (laid under the island)
  art/reef/coralwall.png    a reef wall from the front, tiling left to right (wrapped round the island's base)
An asset module (build.mjs ASSET_MODULES): the desktop build serves the pictures as files."""
import base64, io, json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
def pack(key, p, width, q):
    if not os.path.exists(p): print('missing', p); return
    im = Image.open(p).convert('RGB')
    if im.width > width: im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=q, method=6)
    out[key] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode(); print(key, im.size, len(buf.getvalue()) // 1024, 'KB')
pack('seabed', os.path.join(ROOT, 'art/reef/seabed_top.png'), 2048, 82)
pack('wall', os.path.join(ROOT, 'art/reef/coralwall.png'), 2048, 82)
open(os.path.join(ROOT, 'src/data/reef-backdrop.js'), 'w').write(
    '// Generated by tools/build-reef-backdrop.py from art/reef/seabed_top.png and coralwall.png (Blender). Do not edit by hand.\n'
    'export const REEF_BACKDROP = ' + json.dumps(out) + ';\n')
