#!/usr/bin/env python3
"""Card pack pictures: art/pack/pack_render.png (Blender, Cycles, transparent) → src/data/pack-art.js
The render is cropped to the bag and cut along a jagged tear line just under the top seal into two layers of the same
size: `body` (everything below the line) and `strip` (the torn-off top). `tear` = the line's height as a fraction."""
import base64, io, json, math, pathlib
from PIL import Image, ImageDraw
ROOT = pathlib.Path(__file__).resolve().parent.parent
im = Image.open(ROOT / 'art/pack/pack_render.png').convert('RGBA')
bb = im.split()[3].point(lambda a: 255 if a > 8 else 0).getbbox()
pad = 6
im = im.crop((bb[0] - pad, bb[1] - pad, bb[2] + pad, bb[3] + pad))
W, H = 600, round(600 * im.height / im.width)
im = im.resize((W, H), Image.LANCZOS)
top = pad * W / (bb[2] - bb[0] + 2 * pad)
inner = H - 2 * top
tear = (top + inner * 0.118) / H
ty = tear * H
pts = [(0, 0), (W, 0)]
x = W
k = 0
while x > 0:
    pts.append((x, ty + (5 if k % 2 else -4) + 2 * math.sin(x * 0.05)))
    x -= 14; k += 1
pts.append((0, ty))
mask = Image.new('L', (W, H), 0); ImageDraw.Draw(mask).polygon(pts, fill=255)
a = im.split()[3]
from PIL import ImageChops
strip = im.copy(); strip.putalpha(ImageChops.multiply(a, mask))
body = im.copy(); body.putalpha(ImageChops.multiply(a, ImageChops.invert(mask)))
def uri(img):
    b = io.BytesIO(); img.save(b, 'WEBP', quality=86, method=6); return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
out = {'body': uri(body), 'strip': uri(strip), 'tear': round(tear, 4)}
js = '// Generated by tools/build-pack-art.py from art/pack/pack_render.png (Blender). Do not edit by hand.\nexport const PACK_ART = ' + json.dumps(out) + ';\n'
(ROOT / 'src/data/pack-art.js').write_text(js)
print('pack-art.js', len(js) // 1024, 'KB', 'tear', out['tear'], (W, H))
