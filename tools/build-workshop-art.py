#!/usr/bin/env python3
"""Pack the workshop's Blender renders (tools/blender/workshop_art.py) into src/data/workshop-art.js.
   python3 tools/build-workshop-art.py <render dir>
   python3 tools/build-workshop-art.py <render dir> --add   (only the renders in that dir, merged into the existing file)
The machine, its lever and the jars keep their full canvas (the game places things on them by the points in meta.json);
the things and the stations are trimmed to what they show. Everything becomes webp (alpha) as data URLs."""
import sys, os, io, json, base64
from PIL import Image

src = sys.argv[1]; ADD = '--add' in sys.argv
meta = json.load(open(os.path.join(src, 'meta.json')))
KEEP = lambda n: n in ('machine', 'machine_lever') or n.startswith('jar_')

CROP = {}   # the machine and its lever share one crop (the lever's pivot must stay on the machine)
def machine_box():
    a = Image.open(os.path.join(src, 'machine.png')).split()[3].point(lambda v: 255 if v > 40 else 0); b = a.getbbox()
    l = Image.open(os.path.join(src, 'machine_lever.png')).split()[3].point(lambda v: 255 if v > 40 else 0).getbbox()
    if l: b = (min(b[0], l[0]), min(b[1], l[1]), max(b[2], l[2]), max(b[3], l[3]))
    pad = 6; return (max(0, b[0] - pad), max(0, b[1] - pad), b[2] + pad, b[3] + pad)
def pack(name, maxw=None, q=84):
    im = Image.open(os.path.join(src, name + '.png')).convert('RGBA')
    if name in ('machine', 'machine_lever'):
        CROP.setdefault('m', machine_box()); im = im.crop(CROP['m'])
    if name == 'wall': im = im.crop((52, 0, im.width - 52, im.height)).convert('RGB')
    if not KEEP(name) and name != 'wall':
        a = im.split()[3].point(lambda v: 255 if v > 10 else 0); box = a.getbbox()
        if box:
            pad = 4; box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad)); im = im.crop(box)
    if maxw and im.width > maxw: im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), im.size

out = {'things': {}, 'st': {}, 'jar': {}, 'pieces': {}, 'tests': {}, 'clients': {}, 'meta': {}}
if ADD:   # keep everything already packed; the new renders replace or join it
    old = open('src/data/workshop-art.js').read(); out = json.loads(old[old.index('{'):old.rindex('}') + 1])
total = 0
for f in sorted(os.listdir(src)):
    if not f.endswith('.png'): continue
    n = f[:-4]
    if n == 'jars': continue
    url, size = pack(n, 1280, 74) if n == 'wall' else pack(n, 220 if n.startswith('t_') else 150 if n[:2] in ('p_', 'm_', 's_', 'c_') else None)
    total += len(url)
    if n.startswith('t_'): out['things'][n[2:]] = url
    elif n.startswith('st_'): out['st'][n[3:]] = url
    elif n[:2] in ('p_', 'm_'): out['pieces'][n[2:]] = url
    elif n.startswith('s_'): out['tests'][n[2:]] = url
    elif n.startswith('c_'): out['clients'][n[2:]] = url
    elif n.startswith('jar_'): out['jar'][n[4:]] = url
    elif n == 'machine_lever': out['lever'] = url
    else: out[n] = url
    if n in meta: out['meta'][n] = meta[n]
if not ADD or 'm' in CROP: out['machineBox'] = list(CROP.get('m', ()))
js = ('// generated by tools/build-workshop-art.py from tools/blender/workshop_art.py renders: the workshop\'s machines, things,\n'
      '// stations and the weekly jar, drawn in Blender (1.4.4, Avi 5.11). Points in `meta` are pixels on each full canvas.\n'
      'export const WS_ART = ' + json.dumps(out, ensure_ascii=False) + ';\n')
open('src/data/workshop-art.js', 'w').write(js)
print(f'workshop-art.js: {len(js) // 1024} KB, {len(out["things"])} things, {len(out["st"])} stations, {len(out["jar"])} jars')
