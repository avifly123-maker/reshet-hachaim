// the cards of ניצוץ's nature mixer (1.4.4 set 3) -> src/data/workshop/nature-cards.js
// Every species of the five places that has its own traits (src/data/inventions.js TRAITS) and a card painting, with
// its name, its beginners' name (NAMES_K) and its traits. Made from the zones' data so the workshop pack does not load
// them. usage: node tools/make-workshop-cards.mjs
import fs from 'fs';
const inv = await import('../src/data/inventions.js');
const ik = await import('../src/data/inventions-kids.js');
const { CARD_ART } = await import('../src/data/card-art.js');
const { ZONE_IDS } = await import('../src/data/zones.js');
const out = [];
for (const z of ZONE_IDS) {
  const m = await import(`../src/data/${z}.js`);
  const B = Object.values(m).find((v) => v && Array.isArray(v.species));
  for (const s of B.species) if (inv.TRAITS[s.id] && CARD_ART[s.id]) out.push({ id: s.id, z, n: s.name, k: ik.NAMES_K[s.name] || s.name, tr: inv.TRAITS[s.id] });
}
fs.writeFileSync('src/data/workshop/nature-cards.js', '// generated by tools/make-workshop-cards.mjs: the nature mixer\'s cards (id, zone, name, beginners\' name, traits)\nexport const NATURE_CARDS = ' + JSON.stringify(out) + ';\n');
console.log('nature cards:', out.length);
