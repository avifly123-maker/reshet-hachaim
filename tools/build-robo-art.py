# Packs the portraits of רובו־דע (art/robo/*.png, made by tools/robo-portrait/render.py) into src/data/robo-art.js:
# every frame cropped to the same box (so swapping frames never jumps), as transparent webp. Used by src/ui/robo-guide.js.
import base64, io, json, pathlib
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / 'art' / 'robo'
frames = {p.stem: Image.open(p).convert('RGBA') for p in sorted(SRC.glob('*.png'))}
box = None
for im in frames.values():
    b = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
    box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
pad = 10; box = (max(0, box[0] - pad), max(0, box[1] - pad), box[2] + pad, box[3] + pad)
out = {}
for k, im in frames.items():
    c = im.crop(box); w = 300; h = round(c.height * w / c.width); c = c.resize((w, h), Image.LANCZOS)
    buf = io.BytesIO(); c.save(buf, 'WEBP', quality=88, method=6); out[k] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
w, h = 300, round((box[3] - box[1]) * 300 / (box[2] - box[0]))
js = ('// GENERATED by tools/build-robo-art.py from art/robo/ (tools/robo-portrait/render.py: his real model, the lab\'s) – do not edit.\n'
      '// Portraits of רובו־דע for the guide: idle-* and wave-* frames (happy, normal, talk1, talk2, blink, wow, curious, oops).\n'
      f'export const ROBO_ART = {{ w: {w}, h: {h}, frames: {json.dumps(out)} }};\n')
(ROOT / 'src' / 'data' / 'robo-art.js').write_text(js)
print('robo-art', len(out), 'frames', w, 'x', h, round(len(js) / 1024), 'KB')
