#!/usr/bin/env python3
"""Turn the Blender top-down shadow bake (art/shadow/tree_shadow.png, grey ground with a dappled crown shadow)
into an alpha sprite (white, alpha = shadow strength) → src/data/tree-shadow.js."""
import base64, io, os
import numpy as np
from PIL import Image, ImageFilter
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = Image.open(os.path.join(ROOT, 'art', 'shadow', 'tree_shadow.png')).convert('L')
a = np.asarray(src, dtype=np.float32)
n = a.shape[0]; yy, xx = np.mgrid[0:n, 0:n]; r = np.hypot(xx - n / 2, yy - n / 2) / (n / 2)
bg = np.median(a[r > 0.95])
sh = np.clip((bg - a) / bg, 0, 1)
# remove the hard trunk dot: replace the centre with the surrounding ring's mean
ring = sh[(r > 0.07) & (r < 0.12)].mean()
sh = np.where(r < 0.075, ring, sh)
sh = np.asarray(Image.fromarray((sh * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2)), dtype=np.float32) / 255
sh /= max(sh.max(), 1e-3)
sh *= np.clip((1 - r) / 0.12, 0, 1)                      # guaranteed transparent border
out = np.zeros((n, n, 4), np.uint8); out[..., :3] = 255; out[..., 3] = (sh * 255 + 0.5).astype(np.uint8)
im = Image.fromarray(out, 'RGBA').resize((128, 128), Image.LANCZOS)
b = io.BytesIO(); im.save(b, 'PNG', optimize=True)
url = 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()
open(os.path.join(ROOT, 'src', 'data', 'tree-shadow.js'), 'w').write(
    '// Generated by tools/build-tree-shadow.py from art/shadow/tree_shadow.png (Blender bake). Do not edit by hand.\n'
    f'export const TREE_SHADOW = "{url}";\n')
im.save('ts_sprite.png')
print('sprite', len(b.getvalue()), 'bytes')
