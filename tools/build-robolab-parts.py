#!/usr/bin/env python3
"""Robot-lab tools from Blender -> src/data/robolab-parts.js
Input: art/robolab/parts_export.json, written by rl_export() in tools/blender/robolab_kit.py (on the owner's PC):
  { bases: { robot|drone|sub: { slots: {slot: {p, n}}, spin: {name: {at, rot, slots}}, sockets: {name: {at, yaw}} } },
    parts: { id: { slots: {slot: {p, n}} } } }
  p and n are flat triangle lists (three.js axes, metres). Here each slot mesh is welded (same position, normal),
  positions are quantised to int16 against the mesh's own box, normals to int8, indices uint16; all base64.
Output: export const RL_PARTS = { bases: {...}, parts: {...} } (decoded by src/robolab/three/parts3d.js).
usage: python3 tools/build-robolab-parts.py"""
import json, base64, struct, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'art/robolab/parts_export.json'
OUT = ROOT / 'src/data/robolab-parts.js'
FLIP = False

def weld(p, n):
    idx = {}; P = []; N = []; I = []
    for k in range(len(p) // 3):
        key = (round(p[3*k], 4), round(p[3*k+1], 4), round(p[3*k+2], 4), round(n[3*k], 2), round(n[3*k+1], 2), round(n[3*k+2], 2))
        j = idx.get(key)
        if j is None:
            j = idx[key] = len(P) // 3; P += p[3*k:3*k+3]; N += n[3*k:3*k+3]
        I.append(j)
    return P, N, I

def pack(m):
    P, N, I = weld(m['p'], m['n'])
    if FLIP: I = [I[k + d] for k in range(0, len(I), 3) for d in (0, 2, 1)]   # exports before 29.10 had reversed triangles
    nv = len(P) // 3
    assert nv < 65536, 'too many vertices in one slot mesh'
    lo = [min(P[i::3]) for i in range(3)]; hi = [max(P[i::3]) for i in range(3)]
    sc = [(hi[i] - lo[i]) or 1e-6 for i in range(3)]
    q = [int(round((P[3*v+i] - lo[i]) / sc[i] * 65534 - 32767)) for v in range(nv) for i in range(3)]
    nq = [max(-127, min(127, int(round(x * 127)))) for x in N]
    b = lambda fmt, arr: base64.b64encode(struct.pack('<%d%s' % (len(arr), fmt), *arr)).decode()
    return {'lo': [round(x, 4) for x in lo], 'sc': [round(x, 5) for x in sc], 'p': b('h', q), 'n': b('b', nq), 'i': b('H', I)}, nv, len(I) // 3

def main():
    global FLIP
    D = json.load(open(SRC))
    FLIP = D.get('winding') != 'ccw'
    out = {'bases': {}, 'parts': {}}; tv = tt = 0
    for k, B in D['bases'].items():
        o = {'slots': {}, 'spin': {}, 'sockets': B['sockets']}
        for sl, m in B['slots'].items():
            o['slots'][sl], v, t = pack(m); tv += v; tt += t
        for name, S in B['spin'].items():
            o['spin'][name] = {'at': S['at'], 'rot': S['rot'], 'slots': {}}
            for sl, m in S['slots'].items():
                o['spin'][name]['slots'][sl], v, t = pack(m); tv += v; tt += t
        out['bases'][k] = o
    for k, Pt in D['parts'].items():
        o = {'slots': {}}
        for sl, m in Pt['slots'].items():
            o['slots'][sl], v, t = pack(m); tv += v; tt += t
        out['parts'][k] = o
    js = ('// generated by tools/build-robolab-parts.py from art/robolab/parts_export.json (Blender: tools/blender/robolab_kit.py)\n'
          '// the robot lab\'s tools and their parts, mesh per material slot; decoded by src/robolab/three/parts3d.js\n'
          'export const RL_PARTS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    OUT.write_text(js)
    print('robolab parts: %d bases, %d parts, %d vertices, %d triangles, %d KB' % (len(out['bases']), len(out['parts']), tv, tt, len(js) // 1024))

if __name__ == '__main__':
    main()
