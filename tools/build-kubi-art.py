#!/usr/bin/env python3
"""Kubi's portraits for the guide's bubble -> src/data/kubi-art.js
Input: art/robolab/kubi/kubi_idle.png, kubi_wave.png (Blender: kubi_portraits() in tools/blender/robolab_wk.py, 300x446,
transparent, his screen dark). Both are cropped to the same box round him and stored as webp; the screen's place
(normalised x, y, w, h in the cropped picture) is found from the dark glass of the screen, so the game can draw his live
face there (src/ui/kubi-face.js). Output: export const KUBI_ART = { w, h, screen: {x,y,w,h}, frames: { idle, wave } }
usage: python3 tools/build-kubi-art.py"""
import base64, io, json, pathlib
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'art/robolab/kubi'
OUT = ROOT / 'src/data/kubi-art.js'
ims = {k: Image.open(SRC / ('kubi_%s.png' % k)).convert('RGBA') for k in ('idle', 'wave')}
box = None
for im in ims.values():
    b = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
    box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
pad = 6; box = (max(0, box[0] - pad), max(0, box[1] - pad), box[2] + pad, box[3] + pad)
crop = {k: im.crop(box) for k, im in ims.items()}
W, H = crop['idle'].size
# the screen: the biggest run of dark glass in the upper half (dark, opaque pixels)
im = crop['idle']; px = im.load()
xs, ys = [], []
for y in range(int(H * 0.55)):
    for x in range(W):
        r, g, b, a = px[x, y]
        if a > 200 and r + g + b < 290 and b >= r: xs.append(x); ys.append(y)   # the bluish dark glass (its glint is lighter)
x0, x1 = sorted(xs)[len(xs) // 50], sorted(xs)[-len(xs) // 50 - 1]; y0, y1 = sorted(ys)[len(ys) // 50], sorted(ys)[-len(ys) // 50 - 1]
screen = {'x': round(x0 / W, 4), 'y': round(y0 / H, 4), 'w': round((x1 - x0) / W, 4), 'h': round((y1 - y0) / H, 4)}
frames = {}
for k, c in crop.items():
    b = io.BytesIO(); c.save(b, 'WEBP', quality=85, method=6); frames[k] = 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
OUT.write_text('// generated by tools/build-kubi-art.py from art/robolab/kubi (Blender: kubi_portraits in tools/blender/robolab_wk.py)\n'
               '// Kubi\'s portraits for the guide\'s bubble; his face is drawn live on `screen` (src/ui/kubi-face.js)\n'
               'export const KUBI_ART = ' + json.dumps({'w': W, 'h': H, 'screen': screen, 'frames': frames}, separators=(',', ':')) + ';\n', encoding='utf-8')
print('kubi art:', W, 'x', H, screen, '%d KB' % (OUT.stat().st_size // 1024))
