#!/usr/bin/env python3
"""Pack the workshop's look-around room (tools/blender/workshop_room.py) into src/data/workshop-room-art.js.
   python3 tools/build-workshop-room.py <render dir>      (reads room_pano.png and room.json)
The panorama goes in as one webp; the places keep the points the game needs (the ring on each place and ניצוץ's stop)."""
import sys, os, io, json, base64
from PIL import Image
src = sys.argv[1]
info = json.load(open(os.path.join(src, 'room.json')))
im = Image.open(os.path.join(src, 'room_pano.png')).convert('RGB')
b = io.BytesIO(); im.save(b, 'WEBP', quality=78, method=6)
out = {'pano': 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), 'eye': info['eye'], 'places': info['places'], 'size': list(im.size)}
js = ('// generated by tools/build-workshop-room.py from tools/blender/workshop_room.py: the workshop as a room to look around in\n'
      '// (an equirectangular panorama from its middle, the rainforest outside its windows) and the points of its seven places,\n'
      '// in three\'s axes. Drawn by src/workshop/room3d.js.\n'
      'export const WS_ROOM = ' + json.dumps(out, ensure_ascii=False) + ';\n')
open('src/data/workshop-room-art.js', 'w').write(js)
print(f'workshop-room-art.js: {len(js) // 1024} KB, picture {im.size[0]}x{im.size[1]}')
