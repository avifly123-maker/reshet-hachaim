# The picture on the workshop's door in the start screen (8.11, Avi: the old door, ניצוץ alone on orange, was not nice).
#   python3 tools/blender/workshop_room.py <out> 960 48 door   (headless, ~2.5 min) → cp <out>/door.png art/workshop/door.png
#   python3 tools/build-workshop-door.py → src/data/workshop-door-art.js (ניצוץ's portrait is laid over it in the page)
import base64, io, os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
im = Image.open(os.path.join(ROOT, 'art/workshop/door.png')).convert('RGB')
im = im.resize((720, round(720 * im.height / im.width)), Image.LANCZOS)
b = io.BytesIO(); im.save(b, 'WEBP', quality=80, method=6)
uri = 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
out = os.path.join(ROOT, 'src/data/workshop-door-art.js')
open(out, 'w').write('// generated by tools/build-workshop-door.py from art/workshop/door.png (tools/blender/workshop_room.py door)\nexport const WS_DOOR = ' + repr(uri).replace("'", '"') + ';\n')
print(out, len(uri))
