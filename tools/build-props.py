#!/usr/bin/env python3
"""Blender props → src/data/props.js
Input: art/props/props_export.json, written by the Blender session (Documents/reshet-hachaim-blender/props_and_tools.blend,
       helper code in tools/blender/props.py). Every part: p (xyz, Y-up), n (flat face normals), c (sRGB 0..255), i.
Output: one compact module. Positions are quantised to int16 against the part's own bounding box, normals to int8,
        colours stay uint8, indices uint16 – all base64. Parts listed in SMOOTH get averaged (smooth) normals here.
usage: python3 tools/build-props.py"""
import json, base64, struct, math, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'art/props/props_export.json'
OUT = ROOT / 'src/data/props.js'
SMOOTH = {'river_stones', 'mush_grove', 'mush_amazon', 'acorns', 'carob_pods',
          'drone.body', 'drone.gimbal', 'drone.eye', 'drone.led', 'robot.body', 'robot.head', 'robot.eye', 'robot.beacon', 'robot.tracks'}

def smooth_normals(p, n, i):
    # average the face normals of corners that share a position (keeps colour seams)
    acc = {}
    for k in range(len(p) // 3):
        key = (round(p[3*k], 3), round(p[3*k+1], 3), round(p[3*k+2], 3))
        a = acc.setdefault(key, [0.0, 0.0, 0.0]); a[0] += n[3*k]; a[1] += n[3*k+1]; a[2] += n[3*k+2]
    out = []
    for k in range(len(p) // 3):
        a = acc[(round(p[3*k], 3), round(p[3*k+1], 3), round(p[3*k+2], 3))]
        l = math.sqrt(a[0]**2 + a[1]**2 + a[2]**2) or 1
        out += [a[0]/l, a[1]/l, a[2]/l]
    return out

def dedupe(p, n, c, i):
    idx = {}; P = []; N = []; C = []; I = []
    for v in i:
        key = (round(p[3*v], 4), round(p[3*v+1], 4), round(p[3*v+2], 4), round(n[3*v], 2), round(n[3*v+1], 2), round(n[3*v+2], 2), c[3*v], c[3*v+1], c[3*v+2])
        if key not in idx:
            idx[key] = len(P) // 3; P += p[3*v:3*v+3]; N += n[3*v:3*v+3]; C += c[3*v:3*v+3]
        I.append(idx[key])
    return P, N, C, I

def pack(part, name):
    p, n, c, i = part['p'], part['n'], part['c'], part['i']
    if name in SMOOTH:
        n = smooth_normals(p, n, i)
        p, n, c, i = dedupe(p, n, c, i)
    lo = [min(p[k::3]) for k in range(3)]; hi = [max(p[k::3]) for k in range(3)]
    sc = [(hi[k] - lo[k]) / 65534 or 1e-6 for k in range(3)]
    q = b''.join(struct.pack('<h', int(round((p[3*v+k] - lo[k]) / sc[k])) - 32767) for v in range(len(p)//3) for k in range(3))
    qn = b''.join(struct.pack('<b', max(-127, min(127, int(round(x * 127))))) for x in n)
    qc = bytes(c)
    qi = b''.join(struct.pack('<H', x) for x in i)
    b64 = lambda b: base64.b64encode(b).decode()
    return {'o': [round(x, 5) for x in lo], 's': [round(x, 9) for x in sc], 'p': b64(q), 'n': b64(qn), 'c': b64(qc), 'i': b64(qi)}

data = json.load(open(SRC))
ground = {k: pack(v, k) for k, v in sorted(data['ground'].items())}
tools = {r: {k.split('.', 1)[1]: pack(v, k) for k, v in sorted(parts.items())} for r, parts in sorted(data['tools'].items())}
js = ('// GENERATED by tools/build-props.py from art/props/props_export.json (modelled in Blender) – do not edit.\n'
      '// Low-poly vertex-coloured props: ground details (logs, rocks, river stones, mushrooms, fallen fruit) and the\n'
      '// tool models (drone, rescue robot, nest box). Decoded by src/world/props.js.\n'
      'export const GROUND_PROPS = ' + json.dumps(ground, separators=(',', ':')) + ';\n'
      'export const TOOL_PROPS = ' + json.dumps(tools, separators=(',', ':')) + ';\n')
OUT.write_text(js)
print(f'wrote {OUT.relative_to(ROOT)}: {len(js)/1024:.1f} KB, ground {len(ground)}, tools {sum(len(v) for v in tools.values())} parts')
