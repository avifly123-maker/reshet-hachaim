#!/usr/bin/env python3
"""Pack the Blender horizon panoramas into src/data/panorama.js.

Inputs (art/pano/): <biome>_q0..q3.png  – four 90° RGBA quarters (equirectangular strip, longitude -180..180)
                    <biome>_mist.png    – the Blender mist pass for the whole strip (any width)
                    <biome>.json        – {"lat": [min,max] degrees, "haze": [r,g,b] linear haze colour as baked, "mist_gain": k, "exposure": ev}
Output: PANO[biome] = { img, mist, lat, haze, rot } with webp data URLs.
"""
import base64, io, json, os, sys
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'pano')
OUT = os.path.join(ROOT, 'src', 'data', 'panorama.js')
WIDTH = int(os.environ.get('PANO_W', 8192))

def srgb_to_lin(c):
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)

def data_url(im, **kw):
    b = io.BytesIO(); im.save(b, 'WEBP', **kw)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), len(b.getvalue())

pano = {}
for biome in ('amazon', 'grove', 'reef'):
    qs = [os.path.join(ART, f'{biome}_q{i}.png') for i in range(4)]
    if not all(os.path.exists(q) for q in qs):
        continue
    meta = json.load(open(os.path.join(ART, f'{biome}.json')))
    parts = [Image.open(q).convert('RGBA') for q in qs]
    h = parts[0].height
    strip = Image.new('RGBA', (sum(p.width for p in parts), h))
    x = 0
    for p in parts:
        strip.paste(p, (x, 0)); x += p.width
    if strip.width != WIDTH:
        strip = strip.resize((WIDTH, round(h * WIDTH / strip.width)), Image.LANCZOS)
    img_url, n1 = data_url(strip, quality=meta.get('quality', 80), alpha_quality=90, method=6)
    # mist pass: stored through the Standard view transform → decode to the linear factor actually used for the haze mix
    mist = np.asarray(Image.open(os.path.join(ART, f'{biome}_mist.png')).convert('L'), dtype=np.float32) / 255.0
    m = np.clip(srgb_to_lin(mist) / (2 ** meta.get('exposure', 0.0)) * meta.get('mist_gain', 1.0), 0, 1)
    mim = Image.fromarray((m * 255 + 0.5).astype(np.uint8), 'L').convert('RGB')
    mw = WIDTH // 4
    mim = mim.resize((mw, max(8, round(mim.height * mw / mim.width))), Image.LANCZOS)
    mist_url, n2 = data_url(mim, quality=88, method=6)
    pano[biome] = {'img': img_url, 'mist': mist_url, 'lat': meta['lat'], 'haze': meta['haze'], 'rot': meta.get('rot', 0)}
    print(f'{biome}: strip {strip.size} {n1 // 1024} KB, mist {mim.size} {n2 // 1024} KB')

with open(OUT, 'w') as f:
    f.write('// Generated by tools/build-panorama.py from art/pano/ (Blender renders). Do not edit by hand.\n')
    f.write('export const PANO = ' + json.dumps(pano) + ';\n')
print('wrote', OUT, os.path.getsize(OUT) // 1024, 'KB')
