#!/usr/bin/env python3
"""Pack the Blender island renders (art/islands/<biome>.png) into src/data/island-art.js as webp data URLs."""
import base64, io, json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for b in ('amazon', 'grove', 'reef'):
    p = os.path.join(ROOT, 'art', 'islands', b + '.png')
    if not os.path.exists(p): continue
    im = Image.open(p).convert('RGB')
    if im.width > 960: im = im.resize((960, round(im.height * 960 / im.width)), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=80, method=6)
    out[b] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    print(b, im.size, len(buf.getvalue()) // 1024, 'KB')
open(os.path.join(ROOT, 'src', 'data', 'island-art.js'), 'w').write(
    '// Generated by tools/build-island-art.py from art/islands/*.png (Blender renders). Do not edit by hand.\n'
    'export const ISLAND_ART = ' + json.dumps(out) + ';\n')
