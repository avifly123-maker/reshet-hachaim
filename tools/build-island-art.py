#!/usr/bin/env python3
"""Pack the island pictures into src/data/island-art.js as webp data URLs.
  <biome>     art/islands/<biome>.png            Blender renders (the research hub's case cards)
  c_<biome>   art/islands/carousel/<biome>.png   the island alone on a transparent background (start-screen carousel;
                                                 rendered from the game over black and white: tools/render-island.py; the Amazon one gets a shadow lift)
  lab         art/lab/st_home.png                the lab of רובו־דע (the start screen's science tab)"""
import base64, io, json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
def pack(key, p, width, q, alpha=False):
    if not os.path.exists(p): return
    im = Image.open(p).convert('RGBA' if alpha else 'RGB')
    if im.width > width: im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=q, method=6, alpha_quality=90)
    out[key] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    print(key, im.size, len(buf.getvalue()) // 1024, 'KB')
for b in ('amazon', 'grove', 'reef'):
    pack(b, os.path.join(ROOT, 'art', 'islands', b + '.png'), 960, 80)
    pack('c_' + b, os.path.join(ROOT, 'art', 'islands', 'carousel', b + '.png'), 1000, 84, alpha=True)
pack('lab', os.path.join(ROOT, 'art', 'lab', 'st_home.png'), 760, 80)
open(os.path.join(ROOT, 'src', 'data', 'island-art.js'), 'w').write(
    '// Generated by tools/build-island-art.py from art/islands/ and art/lab/st_home.png. Do not edit by hand.\n'
    'export const ISLAND_ART = ' + json.dumps(out) + ';\n')
