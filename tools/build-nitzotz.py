#!/usr/bin/env python3
"""ניצוץ from Blender -> src/data/nitzotz-model.js
Input: art/workshop/nitzotz_export.json, written by nz_export() in tools/blender/nitzotz.py (tools/nitzotz-build.py runs it headless): a puppet of
joints { name, at, rot, slots: {slot: {p, n}}, sockets, kids }. Meshes are packed like the tools (build-robolab-parts.py).
usage: python3 tools/build-nitzotz.py"""
import json, pathlib, importlib.util
ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location('brp', ROOT / 'tools/build-robolab-parts.py'); brp = importlib.util.module_from_spec(spec); spec.loader.exec_module(brp)
SRC = ROOT / 'art/workshop/nitzotz_export.json'
OUT = ROOT / 'src/data/nitzotz-model.js'

def walk(j, tot):
    o = {'name': j['name'], 'at': j['at'], 'rot': j['rot'], 'slots': {}, 'sockets': j.get('sockets', {}), 'kids': []}
    for sl, m in j['slots'].items():
        o['slots'][sl], v, t = brp.pack(m); tot[0] += v; tot[1] += t
    o['kids'] = [walk(k, tot) for k in j['kids']]
    return o

def main():
    D = json.load(open(SRC)); brp.FLIP = D.get('winding') != 'ccw'
    tot = [0, 0]; P = walk(D['puppet'], tot)
    js = ('// generated by tools/build-nitzotz.py from art/workshop/nitzotz_export.json (Blender: tools/blender/nitzotz.py)\n'
          '// ניצוץ, the inventors\' workshop\'s guide: a puppet of joints (the bulb, two gloves), meshes per material slot; built by src/workshop/nitzotz.js\n'
          'export const NITZOTZ_MODEL = ' + json.dumps(P, separators=(',', ':')) + ';\n')
    OUT.write_text(js)
    print('nitzotz: %d vertices, %d triangles, %d KB' % (tot[0], tot[1], len(js) // 1024))

if __name__ == '__main__':
    main()
