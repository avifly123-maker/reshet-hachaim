#!/usr/bin/env python3
"""Blender reef flora (art/reef/flora/<id>.json, from tools/blender/reef_flora.py) → src/data/reef-flora.js
Every model variant: positions quantised to int16 in its bounding box, normals int8, colours uint8 (sRGB, AO baked in),
indices uint16 (uint32 when needed) – base64 – plus height, perch points and the light crown. Decoded by
src/models/reef-plants.js."""
import json, glob, os, base64, struct
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'art/reef/flora/*.json'))):
    d = json.load(open(f)); vs = []
    for e in d['v']:
        p = np.array(e['p'], np.float32).reshape(-1, 3); n = np.array(e['n'], np.float32).reshape(-1, 3)
        c = np.array(e['c'], np.uint8); i = np.array(e['i'], np.uint32)
        lo = p.min(0); hi = p.max(0); sc = np.maximum((hi - lo) / 65534, 1e-7)
        q = (np.round((p - lo) / sc) - 32767).astype('<i2')
        nn = np.clip(np.round(n * 127), -127, 127).astype('i1')
        idx = i.astype('<u2') if len(p) < 65536 else i.astype('<u4')
        b64 = lambda a: base64.b64encode(a.tobytes()).decode()
        vs.append(dict(o=[round(float(x), 5) for x in lo], s=[float('%.6g' % x) for x in sc], p=b64(q), n=b64(nn), c=b64(c), i=b64(idx),
                       w=4 if len(p) >= 65536 else 2, h=e['h'], perch=e.get('perch', []), crown=e.get('crown'), soft=e.get('soft', False), double=e.get('double', False)))
    out[d['id']] = vs
    print(d['id'], [len(e['i']) // 3 for e in d['v']], 'tris')
dst = os.path.join(ROOT, 'src/data/reef-flora.js')
with open(dst, 'w') as fh:
    fh.write('// GENERATED by tools/build-reef-flora.py from art/reef/flora/*.json (modelled in Blender, tools/blender/reef_flora.py) – do not edit.\n')
    fh.write('export const REEF_FLORA = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(os.path.getsize(dst) // 1024, 'KB')
