#!/usr/bin/env python3
"""ניצוץ's portraits for the guide's bubble -> src/data/nitzotz-art.js (1.4.4 set 2)
They are drawn by the game's own model (src/workshop/nitzotz.js, through the page tests/nitzotz/view.js built by
tools/nitzotz-view.mjs) on a clear background, without his face: the bubble draws the face live on `screen`
(src/ui/nitzotz-face.js), like קוּבִּי's. Frames: idle (gloves beside him), wave (one glove up), idea (bright, after the hop).
Output: export const NITZOTZ_ART = { w, h, screen: {x, y, w, h}, frames: { idle, wave, idea } }
usage: node tools/nitzotz-view.mjs && python3 tools/build-nitzotz-art.py"""
import asyncio, base64, io, json, pathlib
from PIL import Image
from playwright.async_api import async_playwright
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'src/data/nitzotz-art.js'
ARGS = ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist']
POSES = {'idle': ('happy', 0), 'wave': ('wave', 0.7), 'idea': ('idea', 0.9)}
S = 460

async def shoot():
    out = {}
    async with async_playwright() as p:
        b = await p.chromium.launch(args=ARGS); pg = await b.new_page(viewport={'width': S, 'height': S})
        await pg.goto((ROOT / 'shots/nitzotz-view.html').as_uri() + '?portrait=1'); await pg.wait_for_timeout(2500)
        await pg.evaluate("window.__nz.still(true); 1")
        rect = None
        for k, (act, sec) in POSES.items():
            await pg.evaluate(f"window.__nz.set('{act}'); window.__nz.pose({sec}); 1"); await pg.wait_for_timeout(200)
            if k == 'idle': rect = await pg.evaluate("window.__nz.faceRect()")
            out[k] = Image.open(io.BytesIO(await pg.screenshot(omit_background=True))).convert('RGBA')
        await b.close()
    return out, rect

def main():
    ims, rect = asyncio.run(shoot())
    box = None
    for im in ims.values():
        bb = im.getchannel('A').point(lambda a: 255 if a > 10 else 0).getbbox()
        box = bb if box is None else (min(box[0], bb[0]), min(box[1], bb[1]), max(box[2], bb[2]), max(box[3], bb[3]))
    pad = 6; box = (max(0, box[0] - pad), max(0, box[1] - pad), min(S, box[2] + pad), min(S, box[3] + pad))
    W, H = box[2] - box[0], box[3] - box[1]
    scr = {'x': round((rect['x'] * S - box[0]) / W, 4), 'y': round((rect['y'] * S - box[1]) / H, 4), 'w': round(rect['w'] * S / W, 4), 'h': round(rect['h'] * S / H, 4)}
    frames = {}
    for k, im in ims.items():
        c = im.crop(box); buf = io.BytesIO(); c.save(buf, 'WEBP', quality=86, method=6)
        frames[k] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    js = ('// generated by tools/build-nitzotz-art.py (the game\'s own model, src/workshop/nitzotz.js, without his face)\n'
          '// ניצוץ\'s portraits for the guide\'s bubble; his face is drawn live on `screen` (src/ui/nitzotz-face.js)\n'
          'export const NITZOTZ_ART = ' + json.dumps({'w': W, 'h': H, 'screen': scr, 'frames': frames}, separators=(',', ':')) + ';\n')
    OUT.write_text(js)
    print('nitzotz art: %dx%d, screen %s, %d KB' % (W, H, scr, len(js) // 1024))

if __name__ == '__main__':
    main()
